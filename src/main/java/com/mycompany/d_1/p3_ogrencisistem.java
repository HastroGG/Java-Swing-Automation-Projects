    private void tabloGuncelle(ArrayList<Ogrenci> liste) {
        tabloModeli.setRowCount(0); // Tabloyu temizle
        for (Ogrenci ogr : liste) {
            tabloModeli.addRow(new Object[]{
                ogr.getNumara(),
                ogr.getAd(),
                ogr.getSoyad(),});
        }
    }

