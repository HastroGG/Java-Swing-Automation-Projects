    private void btnEkleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEkleActionPerformed
        String ogrNo = txtNumara.getText();
        String ogrAd = txtAd.getText();
        String ogrSoyad = txtSoyad.getText();

        if (!ogrNo.isEmpty() && !ogrAd.isEmpty()) {
            Ogrenci yeniOgrenci = new Ogrenci(ogrNo, ogrAd, ogrSoyad);
            ogrenciListesi.add(yeniOgrenci);
            tabloGuncelle(ogrenciListesi);
        } else {
            JOptionPane.showMessageDialog(this, "Hata! Eksik kısımlar mevcut.");
        }
    }//GEN-LAST:event_btnEkleActionPerformed

    private void btnSilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSilActionPerformed
        if (tblList.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Hata! Öğrenci seçilmedi");
        } else {
            ogrenciListesi.remove(tblList.getSelectedRow());
            tabloGuncelle(ogrenciListesi);
        }
    }//GEN-LAST:event_btnSilActionPerformed

    private void btnGuncelleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuncelleActionPerformed
        if (tblList.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Hata! Öğrenci seçili değil.");
        } else {
            Ogrenci ogr = ogrenciListesi.get(tblList.getSelectedRow());
            ogr.setNumara(txtNumara.getText().trim());
            ogr.setAd(txtAd.getText().trim());
            ogr.setSoyad(txtSoyad.getText().trim());
            tabloGuncelle(ogrenciListesi);
        }
    }//GEN-LAST:event_btnGuncelleActionPerformed

    private void txtAramaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtAramaKeyReleased
        String aranan = txtArama.getText().toLowerCase().trim();
        ArrayList<Ogrenci> filtrelenmisList = new ArrayList<>();

        for (Ogrenci ogr : ogrenciListesi) {
            if (ogr.getAd().toLowerCase().contains(aranan)
                    || ogr.getNumara().toLowerCase().contains(aranan)
                    || ogr.getSoyad().toLowerCase().contains(aranan)) {
                filtrelenmisList.add(ogr);
            }
        }
        tabloGuncelle(filtrelenmisList); 
    }//GEN-LAST:event_txtAramaKeyReleased

