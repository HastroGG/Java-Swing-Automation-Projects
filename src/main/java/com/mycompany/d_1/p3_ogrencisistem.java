    public static class Ogrenci {

        private String ogrNo;
        private String ogrAd;
        private String ogrSoyad;

        //Constructor
        public Ogrenci(String ogrNo, String ogrAd, String ogrSoyad) {
            this.ogrNo = ogrNo;
            this.ogrAd = ogrAd;
            this.ogrSoyad = ogrSoyad;
        }

        //Get-Set kısmı
        public String getNumara() {
            return ogrNo;
        }

        public void setNumara(String ogrNo) {
            this.ogrNo = ogrNo;
        }

        public String getAd() {
            return ogrAd;
        }

        public void setAd(String ogrAd) {
            this.ogrAd = ogrAd;
        }

        public String getSoyad() {
            return ogrSoyad;
        }

        public void setSoyad(String ogrSoyad) {
            this.ogrSoyad = ogrSoyad;
        }

        public String metneCevir() {
            return ogrNo + ";" + ogrAd + ";" + ogrSoyad;
        }

        public static Ogrenci fromFileString(String line) {
            String[] parcalar = line.split(";");
            if (parcalar.length == 3) {
                String ogrNo = parcalar[0];
                String ogrAd = parcalar[1];
                String ogrSoyad = parcalar[2];
                return new Ogrenci(ogrNo, ogrAd, ogrSoyad);
            }
            return null;
        }
    }

